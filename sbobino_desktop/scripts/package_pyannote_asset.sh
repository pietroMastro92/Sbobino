#!/usr/bin/env bash
set -euo pipefail

SCRIPT_DIR=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
PYANNOTE_PORTABLE_RUNTIME_LIB="$SCRIPT_DIR/lib/pyannote_portable_runtime.py"

if [[ $# -ne 3 ]]; then
  echo "Usage: $0 <source_dir> <archive_root_name> <output_zip>" >&2
  exit 1
fi

SOURCE_DIR=$1
ARCHIVE_ROOT_NAME=$2
OUTPUT_ZIP=$3

if [[ ! -d "$SOURCE_DIR" ]]; then
  echo "Source directory not found: $SOURCE_DIR" >&2
  exit 1
fi

assert_portable_runtime() {
  # A package assembled from the wrong machine can look healthy until the
  # Companion installer validates it. Use the same shared strict audit as the
  # generator and the repair tool: architecture, host-managed dependency,
  # LC_RPATH and install-name references, signatures and payload seals.
  # A runtime generated by the pre-October-2026 rpath sanitizer still exposes
  # /opt/homebrew/lib and must fail here, before any archive is written.
  if [[ "$ARCHIVE_ROOT_NAME" != "python" || "$(uname -s)" != "Darwin" ]]; then
    return 0
  fi

  local expected_arch
  case "$(uname -m)" in
    arm64) expected_arch=arm64 ;;
    x86_64) expected_arch=x86_64 ;;
    *) echo "Unsupported macOS packaging architecture: $(uname -m)" >&2; exit 1 ;;
  esac

  python3 "$PYANNOTE_PORTABLE_RUNTIME_LIB" audit "$SOURCE_DIR" --expect-arch "$expected_arch"
}

assert_portable_runtime

mkdir -p "$(dirname "$OUTPUT_ZIP")"
rm -f "$OUTPUT_ZIP"

STAGE_DIR=$(mktemp -d)
trap 'rm -rf "$STAGE_DIR"' EXIT

TARGET_ROOT="$STAGE_DIR/$ARCHIVE_ROOT_NAME"
mkdir -p "$(dirname "$TARGET_ROOT")"
cp -R "$SOURCE_DIR" "$TARGET_ROOT"

ditto -c -k --sequesterRsrc --keepParent "$TARGET_ROOT" "$OUTPUT_ZIP"
echo "Created $OUTPUT_ZIP"
